 * Problem Statement:
 *   Create a full adder: add three bits (a, b, cin) and produce a sum bit
 *   and a carry-out bit.
 *------------------------------------------------------------------------------------------
 * Module Declaration:
 *   module top_module (
 *       input  a, b, cin,
 *       output cout, sum
 *   );
 */
//==========================================================================================
module top_module (
    input  a, b, cin,
    output cout, sum
);

    assign sum  = a ^ b ^ cin; // Sum is the XOR of all three inputs
    assign cout = (a & b) | (cin & (a ^ b)); // Carry-out is generated by the full adder logic  

endmodule
//==========================================================================================
